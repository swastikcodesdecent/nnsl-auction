// Safe helper to trigger Lucide replacement on elements with data-lucide attribute
export function refreshLucideIcons() {
  if (typeof window !== 'undefined' && window.lucide && typeof window.lucide.createIcons === 'function') {
    try {
      window.lucide.createIcons();
    } catch (e) {
      console.warn("Lucide icon generation exception:", e);
    }
  }
}

// Toast notification dispatcher
export function showToast(message, type = 'info', duration = 3500) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast ${type}`;
  toast.innerHTML = `<span>${message}</span>`;
  
  container.appendChild(toast);

  setTimeout(() => {
    toast.style.transition = 'opacity 0.3s ease, transform 0.3s ease';
    toast.style.opacity = '0';
    toast.style.transform = 'translateX(100%)';
    setTimeout(() => toast.remove(), 300);
  }, duration);
}

// Global modal confirmation dialog
export function showConfirmDialog({ title, message, confirmText = 'Confirm', confirmStyle = 'btn-primary', onConfirm }) {
  let modal = document.getElementById('global-confirm-modal');
  if (!modal) {
    modal = document.createElement('div');
    modal.id = 'global-confirm-modal';
    modal.className = 'modal-backdrop';
    modal.innerHTML = `
      <div class="modal-dialog">
        <div class="modal-header">
          <h3 class="modal-title" id="confirm-modal-title">Confirm Action</h3>
          <button class="modal-close" id="confirm-modal-close">&times;</button>
        </div>
        <div class="modal-body" id="confirm-modal-body">
          Are you sure you want to proceed?
        </div>
        <div class="modal-footer">
          <button class="btn btn-secondary" id="confirm-modal-cancel">Cancel</button>
          <button class="btn btn-primary" id="confirm-modal-action">Confirm</button>
        </div>
      </div>
    `;
    document.body.appendChild(modal);
  }

  const titleEl = document.getElementById('confirm-modal-title');
  const bodyEl = document.getElementById('confirm-modal-body');
  const actionBtn = document.getElementById('confirm-modal-action');
  const cancelBtn = document.getElementById('confirm-modal-cancel');
  const closeBtn = document.getElementById('confirm-modal-close');

  titleEl.textContent = title;
  bodyEl.innerHTML = `<p style="font-size: 1rem; color: #e2e8f0;">${message}</p>`;
  actionBtn.textContent = confirmText;
  actionBtn.className = `btn ${confirmStyle}`;

  modal.classList.add('active');

  const cleanup = () => {
    modal.classList.remove('active');
    actionBtn.onclick = null;
    cancelBtn.onclick = null;
    closeBtn.onclick = null;
  };

  actionBtn.onclick = () => {
    cleanup();
    if (typeof onConfirm === 'function') onConfirm();
  };

  cancelBtn.onclick = cleanup;
  closeBtn.onclick = cleanup;
}

// Navigation active item sync
export function setupNavigation(activePageId) {
  const links = document.querySelectorAll('.nav-item a');
  links.forEach(link => {
    if (link.dataset.page === activePageId) {
      link.classList.add('active');
    } else {
      link.classList.remove('active');
    }
  });

  const mobileToggle = document.querySelector('.nav-mobile-toggle');
  const navLinksList = document.querySelector('.nav-links');
  if (mobileToggle && navLinksList) {
    mobileToggle.onclick = () => {
      navLinksList.classList.toggle('show');
    };
  }

  refreshLucideIcons();
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', refreshLucideIcons);
  } else {
    refreshLucideIcons();
  }
}

