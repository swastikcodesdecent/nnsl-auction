// Formats integer currency in INR (Crores, Lakhs, Thousands)
export function formatCurrency(amount, compact = false) {
  if (amount === undefined || amount === null || isNaN(amount)) return '₹ 0';
  const num = Number(amount);

  if (compact) {
    if (Math.abs(num) >= 10000000) { // 1 Crore = 1,00,00,000
      const cr = num / 10000000;
      return `₹ ${Number.isInteger(cr) ? cr : cr.toFixed(2)} Cr`;
    }
    if (Math.abs(num) >= 100000) { // 1 Lakh = 1,00,000
      const lk = num / 100000;
      return `₹ ${Number.isInteger(lk) ? lk : lk.toFixed(2)} Lakh`;
    }
    if (Math.abs(num) >= 1000) {
      return `₹ ${(num / 1000).toFixed(1)}K`;
    }
    return `₹ ${num}`;
  }

  // Full Indian number formatting (e.g. ₹ 2,30,00,000 or ₹ 2,300)
  try {
    const formatted = new Intl.NumberFormat('en-IN', {
      maximumFractionDigits: 0
    }).format(num);
    return `₹ ${formatted}`;
  } catch (e) {
    return `₹ ${num.toLocaleString('en-IN')}`;
  }
}

